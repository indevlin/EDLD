#!/usr/bin/env python3
"""scripts/export_fsd_drives.py — every frame shift drive's jump figures.

    python3 scripts/export_fsd_drives.py              # fetch it, write the table
    python3 scripts/export_fsd_drives.py FILE.json    # from a copy on disk

The figures are Frontier's game data.
"""
from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "fsd_drives.py"
SOURCE = ("https://raw.githubusercontent.com/EDCD/coriolis-data/master/"
          "modules/standard/frame_shift_drive.json")


def load(path: str | None) -> list[dict]:
    if path:
        raw = Path(path).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(SOURCE, timeout=30) as r:
            raw = r.read().decode("utf-8")
    return json.loads(raw)["fsd"]


def build(drives: list[dict]) -> dict[str, tuple]:
    table: dict[str, tuple] = {}
    for d in drives:
        key = str(d["symbol"]).lower()
        row = (float(d["optmass"]), float(d["maxfuel"]),
               float(d["fuelmul"]), float(d["fuelpower"]))
        # The stock drive (it has a Frontier id) wins over a V1 sharing its symbol.
        if key not in table or d.get("edID"):
            table[key] = row
    return dict(sorted(table.items()))


def main() -> None:
    table = build(load(sys.argv[1] if len(sys.argv) > 1 else None))
    lines = [
        '"""',
        "data/fsd_drives.py — frame shift drives' jump figures.",
        "",
        "Generated by scripts/export_fsd_drives.py from EDCD's coriolis-data",
        "modules/standard/frame_shift_drive.json:",
        SOURCE,
        "Do not edit; run the script again.",
        "",
        "symbol (lower case) -> (optimal mass t, max fuel per jump t,",
        "                        fuel multiplier, fuel power)",
        '"""',
        "",
        "FSD_DRIVES: dict[str, tuple[float, float, float, float]] = {",
    ]
    lines += [f"    {k!r}: {v!r}," for k, v in table.items()]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(table)} drives to {OUT}")


if __name__ == "__main__":
    main()
