#!/usr/bin/env python3
"""scripts/export_edam_themes.py — EDLD's built-in themes, as Kotlin for EDAM.

EDAM follows whatever theme EDLD is drawing with, sent in every snapshot.  It
also carries EDLD's built-in themes, so a commander can pick one on the device
and see it before pairing.  Those are generated from core/palette.py by this
script rather than copied by hand, so the two cannot drift:

    python3 scripts/export_edam_themes.py \\
        ~/projects/EDAM/app/src/main/java/com/indevlin/edam/ui/EdldThemes.kt

Run it again whenever a palette changes.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from core.palette import THEME_CHOICES, WIRE_KEYS, wire_theme  # noqa: E402
from core.state import VERSION  # noqa: E402

FIELDS = list(WIRE_KEYS.values())


def _argb(hex_colour: str) -> str:
    h = hex_colour.strip().lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if len(h) != 6:
        raise ValueError(f"not a #rrggbb color: {hex_colour!r}")
    return f"0xFF{h.upper()}"


def render() -> str:
    lines = [
        "// Generated by EDLD's scripts/export_edam_themes.py from core/palette.py",
        f"// (EDLD {VERSION}).  Do not edit: change the palette there and rerun.",
        "package com.indevlin.edam.ui",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "/** EDLD's built-in themes, in the order EDLD's preferences list them. */",
        "val EdldThemes: List<EdldPalette> = listOf(",
    ]
    for _name, tid in THEME_CHOICES:
        t = wire_theme(tid)
        c = t["colors"]
        args = ", ".join(f"{f} = Color({_argb(c[f])})" for f in FIELDS)
        lines.append(f'    EdldPalette("{t["id"]}", "{t["name"]}", {args}),')
    lines.append(")")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if len(argv) > 1:
        out = Path(argv[1]).expanduser()
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print(f"wrote {len(THEME_CHOICES)} themes to {out}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
